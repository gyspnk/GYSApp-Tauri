/** Locale tables other than Indonesian ship as their own chunk. The shell
 * awaits this before rendering (and before switching language) so a stored
 * locale never paints Indonesian first. */
export async function loadLocaleMessages(locale: Locale): Promise<void> {
  if (locale === "id" || Object.keys(messages[locale]).length > 0) return;
  if (locale === "en") {
    const loaded = await import("./i18n-en.js");
    Object.assign(messages.en, loaded.enMessages);
    Object.assign(featureMessages.en, loaded.enFeatureMessages);
    return;
  }
  const loaded = await import("./i18n-zh.js");
  Object.assign(messages.zh, loaded.zhMessages);
  Object.assign(featureMessages.zh, loaded.zhFeatureMessages);
}

export function translate(
  locale: Locale,
  key: string,
  values?: MessageValues,
): string {
  const template =
    messages[locale][key] ??
    featureMessages[locale][key] ??
    messages.id[key] ??
    featureMessages.id[key] ??
    key;
  if (!values) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name)
      ? String(values[name])
      : match,
  );
}
