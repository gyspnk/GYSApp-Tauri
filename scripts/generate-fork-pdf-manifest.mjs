import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
const root = process.env.GYSAPP_FORK_SNAPSHOT;
const sourceCommit = process.env.GYSAPP_FORK_COMMIT ?? "4f0d39b";
if (!root)
  throw new Error(
    "Set GYSAPP_FORK_SNAPSHOT to an immutable GYSAPP-Fork snapshot.",
  );
const raw = JSON.parse(
  await readFile(`${root}/assets/data/index/kr_pdf_manifest.json`, "utf8"),
);
const masterBytes = await readFile(`${root}/${raw.masterPath}`);
const manifest = {
  sourceRepo: "ThenGB/GYSAPP-Fork",
  sourceCommit,
  generatedAt: new Date().toISOString(),
  bookCode: "KR",
  masterPath: raw.masterPath,
  pageCount: raw.pageCount,
  sizeBytes: masterBytes.byteLength,
  sha256: createHash("sha256").update(masterBytes).digest("hex"),
  songs: raw.songs,
};
await mkdir("apps/web/public/offline", { recursive: true });
await writeFile(
  "apps/web/public/offline/fork-hymnal-manifest.json",
  `${JSON.stringify(manifest, null, 2)}\n`,
);
await writeFile(
  "apps/bff/src/fork-pdf-source.ts",
  `/** Generated by scripts/generate-fork-pdf-manifest.mjs; do not edit by hand. */\nexport const forkPdfSource = ${JSON.stringify(
    {
      sourceRepo: manifest.sourceRepo,
      sourceCommit: manifest.sourceCommit,
      masterPath: manifest.masterPath,
      sizeBytes: manifest.sizeBytes,
      sha256: manifest.sha256,
    },
    null,
    2,
  )} as const;\n`,
);
console.log(
  `Generated fork PDF manifest for ${Object.keys(raw.songs).length} songs.`,
);
